import fs from 'node:fs';
import path from 'node:path';
import { marked } from 'marked';

const [date, slug] = process.argv.slice(2);
if (!date || !slug) throw new Error('Usage: node scripts/compile-phase-five-study.mjs YYYY-MM-DD article-slug');
const root = process.cwd();
const draftPath = path.join(root, 'phase-v-writing', `${date}.md`);
const articlePath = path.join(root, 'src/content/articles', `${slug}.json`);
const article = JSON.parse(fs.readFileSync(articlePath, 'utf8'));
const raw = fs.readFileSync(draftPath, 'utf8');
const refs = [];
const locators = {};
const withCitations = raw.replace(/\{\{([a-z0-9-]+)::([^}]+)\}\}/g, (_all, id, locator, offset) => {
  const first = !raw.slice(0, offset).includes(`{{${id}::`);
  if (!refs.includes(id)) refs.push(id);
  locators[id] ??= [];
  if (!locators[id].includes(locator)) locators[id].push(locator);
  const n = refs.indexOf(id) + 1;
  const safe = locator.replaceAll('&', '&amp;').replaceAll('"', '&quot;');
  return `<sup class="source-ref"${first ? ` id="cite-${id}"` : ''}><a href="#source-${id}" aria-label="Source ${n}" title="${safe}">[${n}]</a></sup>`;
});
const body = marked.parse(withCitations, { gfm: true }).trim();
const sections = [...body.matchAll(/<h2 id="([^"]+)">([^<]+)<\/h2>/g)].map(([, id, label]) => ({ id, label }));
const prose = body.replace(/<sup\b[\s\S]*?<\/sup>/g, '').replace(/<p\b[^>]*class="eyebrow"[^>]*>[\s\S]*?<\/p>/g, '').replace(/<h[1-6]\b[\s\S]*?<\/h[1-6]>/g, '').replace(/<[^>]*>/g, ' ').replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n))).replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16))).replace(/&(?:amp|quot|apos|lt|gt);/g, entity => ({'&amp;':'&','&quot;':'"','&apos;':"'",'&lt;':'<','&gt;':'>'})[entity]);
const words = (prose.match(/[\p{L}\p{N}_]+(?:[’'–-][\p{L}\p{N}_]+)*/gu) || []).length;
if (words < 3000 || words > 5000) throw new Error(`${date}: ${words} words, expected 3000–5000`);
if (sections.length < 6 || sections.length > 9) throw new Error(`${date}: ${sections.length} sections, expected 6–9`);
const asides = (body.match(/<aside\b/g) || []).length;
if (asides < 2 || asides > 3) throw new Error(`${date}: ${asides} asides, expected 2–3`);
if (body.includes('{{')) throw new Error(`${date}: unresolved citation marker`);
article.status = 'ready-for-review';
article.subtitle = 'Phase V · The Offensive Exhausted';
article.body = body;
article.sourceIds = refs;
article.sections = sections;
article.sourceLocators = locators;
article.narrativeWordCount = words;
article.substantiveWordCount = words;
article.readingMinutes = Math.ceil(words / 220);
article.researchStatus = 'Complete historical study prepared for editorial review, with claim-level citations and chronology notes.';
article.sourceMethod = 'Numbered notes identify the evidence for specific claims and link to the sources below. Contemporary reports are treated as records of what their authors knew, claimed or intended, not as omniscient accounts. German operational narratives are read alongside Soviet and independent records where available. The Phase V companion map is geographic reference only; it does not claim verified dated military positions.';
article.preparedDate ??= new Date().toISOString().slice(0, 10);
article.revisionDate = new Date().toISOString().slice(0, 10);
delete article.publicationDate;
delete article.reviewedDate;
delete article.reviewedBodySha256;
fs.writeFileSync(articlePath, JSON.stringify(article, null, 2) + '\n');
console.log(`${date}: saved ${words} prose words, ${sections.length} sections, ${asides} asides, ${refs.length} sources`);
